  let current = 'pt';
  function setLang(l) { current = I18N[l] ? l : 'pt'; document && document.documentElement && (document.documentElement.lang = current === 'pt' ? 'pt-BR' : 'en'); }
  function getLang() { return current; }
  function t(key, vars) {
    let s = (I18N[current] && I18N[current][key]);
    if (s === undefined) s = I18N.pt[key];
    if (s === undefined) { if (g.console) console.warn('i18n missing:', key); return key; }
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }
  function locale() { return current === 'pt' ? 'pt-BR' : 'en-US'; }
  function money(cents) {
    return new Intl.NumberFormat(locale(), { style: 'currency', currency: 'BRL' }).format((cents || 0) / 100);
  }
  function date(ts) {
    return new Intl.DateTimeFormat(locale(), { day: '2-digit', month: 'short', year: 'numeric' }).format(new Date(ts));
  }
  function dateTime(ts) {
    return new Intl.DateTimeFormat(locale(), { day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit' }).format(new Date(ts));
  }
  /* "12,50" ou "12.50" -> 1250 centavos; NaN se inválido */
  function parseMoney(str) {
    if (typeof str === 'number') return Math.round(str * 100);
    let s = String(str || '').trim().replace(/[R$\s]/g, '');
    if (!s) return NaN;
    if (s.includes(',') && s.includes('.')) s = s.lastIndexOf(',') > s.lastIndexOf('.') ? s.replace(/\./g, '').replace(',', '.') : s.replace(/,/g, '');
    else s = s.replace(',', '.');
    if (!/^\d*\.?\d{0,2}$/.test(s)) return NaN;
    const n = Math.round(parseFloat(s) * 100);
    return Number.isFinite(n) ? n : NaN;
  }
  function moneyInput(cents) { return ((cents || 0) / 100).toFixed(2).replace('.', current === 'pt' ? ',' : '.'); }

